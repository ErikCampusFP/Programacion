
public class Frase {
	private String in; // inglés.
	private String es; // español.
	
	public Frase(String in, String es) {
		super();
		this.in = in;
		this.es = es;
	}

	public String getIn() {
		return in;
	}

	public void setIn(String in) {
		this.in = in;
	}

	public String getEs() {
		return es;
	}

	public void setEs(String es) {
		this.es = es;
	}
		
}